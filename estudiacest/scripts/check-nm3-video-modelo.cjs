const {chromium}=require('playwright');
const fs=require('fs');
const origin=process.argv[2]||'http://127.0.0.1:8874';
(async()=>{const b=await chromium.launch();const evidence=[];
try{for(const width of [390,1366,3840]){
const p=await b.newPage({viewport:{width,height:950}}),errors=[];
p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
p.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url())});
await p.goto(origin+'/nm3/mi-dia-en-imagenes/',{waitUntil:'domcontentloaded'});
await p.locator('video').evaluate(v=>{v.preload='auto';v.load()});
await p.waitForFunction(()=>document.querySelector('video').readyState>=1,{},{timeout:45000});
const meta=await p.locator('video').evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight}));
if(Math.abs(meta.duration-300)>.04||meta.width!==1280||meta.height!==720)throw Error(JSON.stringify(meta));
await p.locator('video').evaluate(v=>{v.muted=true;return v.play()});
await p.waitForFunction(()=>document.querySelector('video').currentTime>.25);
await p.locator('video').evaluate(v=>{v.pause();v.currentTime=140});
await p.waitForFunction(()=>{const v=document.querySelector('video');return !v.seeking&&Math.abs(v.currentTime-140)<.2&&v.readyState>=2},{},{timeout:45000});
await p.locator('video').screenshot({path:`test-results/mi-dia/video-${origin.includes('127.')?'local':'publico'}-${width}-matematica.png`});
await p.locator('video').evaluate(v=>{v.currentTime=298});
await p.waitForFunction(()=>{const v=document.querySelector('video');return !v.seeking&&Math.abs(v.currentTime-298)<.2&&v.readyState>=2},{},{timeout:45000});
await p.locator('video').evaluate(v=>v.play());
await p.waitForFunction(()=>document.querySelector('video').ended,{},{timeout:12000});
await p.locator('video').evaluate(v=>{v.currentTime=298;v.pause()});
await p.waitForFunction(()=>!document.querySelector('video').seeking);
await p.locator('video').screenshot({path:`test-results/mi-dia/video-${origin.includes('127.')?'local':'publico'}-${width}-cierre.png`});
if(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Desborde');
if(errors.length)throw Error(errors.join('\n'));
evidence.push({width,...meta,inicio:true,matematica:true,cierre:true,sinErrores:true});await p.close();
}fs.writeFileSync('test-results/mi-dia/video-'+(origin.includes('127.')?'local':'publico')+'.json',JSON.stringify(evidence,null,2));console.log('Video: 5:00, reproducción, Matemática y cierre verificados en tres tamaños.');
}finally{await b.close()}})().catch(e=>{console.error(e);process.exitCode=1});
